import java.io.IOException;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.ZoneId;
import java.time.zone.ZoneRulesProvider;
import java.util.TreeSet;

/**
 * Writes the compiler's generated sources, run by the build on the JVM it pins (see build.gradle.kts):
 *
 * - org/drivine/cypher/time/JvmZoneIds.kt: the region ids that JVM's `ZoneId.of` takes, for the platforms whose zone
 *   database is not the JVM's (Kotlin/Native reads the OS's, wasmJs Node's ICU).
 * - org/drivine/cypher/number/DoubleTables.kt: the powers of ten Schubfach writes a double with, and the powers of five
 *   Eisel-Lemire reads one with. Both are exact arithmetic, worked out here with BigInteger.
 *
 *   java gen/Generate.java <output directory>
 */
public class Generate {

    public static void main(String[] args) throws IOException {
        Path out = Path.of(args[0]);
        write(out.resolve("org/drivine/cypher/time/JvmZoneIds.kt"), zoneIds());
        write(out.resolve("org/drivine/cypher/number/DoubleTables.kt"), doubleTables());
    }

    private static void write(Path file, String text) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, text, StandardCharsets.UTF_8);
    }

    private static String zoneIds() {
        TreeSet<String> ids = new TreeSet<>(ZoneId.getAvailableZoneIds());
        String tzdb = ZoneRulesProvider.getVersions("UTC").lastKey();
        String jvm = System.getProperty("java.vendor") + " " + System.getProperty("java.runtime.version");
        return "// Generated by gen/Generate.java from " + jvm + ", tzdb " + tzdb + ". Do not edit.\n"
            + "package org.drivine.cypher.time\n\n"
            + "/** The tzdb release of the JVM the region ids were read from. */\n"
            + "internal const val JVM_TZDB_VERSION = \"" + tzdb + "\"\n\n"
            + "/** The region ids `ZoneId.of` takes on " + jvm + " (" + ids.size() + " ids). */\n"
            + "internal val JVM_ZONE_IDS: Set<String> by lazy { JVM_ZONE_TEXT.split(' ').toHashSet() }\n\n"
            + "private const val JVM_ZONE_TEXT =\n"
            + chunks(String.join(" ", ids)) + "\n";
    }

    /** A long text as Kotlin string literals joined by `+`, of 100 characters or so each. */
    private static String chunks(String text) {
        StringBuilder out = new StringBuilder();
        for (int i = 0; i < text.length(); i += 100) {
            if (i > 0) out.append(" +\n");
            out.append("    \"").append(text, i, Math.min(text.length(), i + 100)).append('"');
        }
        return out.toString();
    }

    // Schubfach's range of k, the decimal exponent of a double's interval, from the least subnormal to the greatest double.
    private static final int K_MIN = -324;
    private static final int K_MAX = 292;
    // Eisel-Lemire's range of decimal exponents: below it a 19-digit number is zero, above it infinite.
    private static final int Q_MIN = -342;
    private static final int Q_MAX = 308;

    private static final BigInteger TWO_64 = BigInteger.ONE.shiftLeft(64);
    private static final BigInteger MASK_63 = BigInteger.ONE.shiftLeft(63).subtract(BigInteger.ONE);

    private static String doubleTables() {
        StringBuilder g = new StringBuilder();
        for (int k = K_MIN; k <= K_MAX; k++) {
            BigInteger value = schubfachPower(-k);
            g.append("    ").append(value.shiftRight(63).longValueExact()).append("L, ")
                .append(value.and(MASK_63).longValueExact()).append("L,\n");
        }
        StringBuilder five = new StringBuilder();
        for (int q = Q_MIN; q <= Q_MAX; q++) {
            BigInteger value = lemirePower(q);
            five.append("    ").append(literal(value.shiftRight(64).longValue())).append(", ")
                .append(literal(value.mod(TWO_64).longValue())).append(",\n");
        }
        return "// Generated by gen/Generate.java. Do not edit.\n"
            + "package org.drivine.cypher.number\n\n"
            + "internal object DoubleTables {\n"
            + "    const val K_MIN = " + K_MIN + "\n"
            + "    const val K_MAX = " + K_MAX + "\n"
            + "    const val Q_MIN = " + Q_MIN + "\n"
            + "    const val Q_MAX = " + Q_MAX + "\n\n"
            + "    /**\n"
            + "     * For each k from K_MIN to K_MAX, g = floor(10^-k × 2^-r) + 1, where r = floor(log2(10^-k)) - 125, so that\n"
            + "     * 2^125 <= g < 2^126: its upper bits g >> 63 and its lower 63 bits, in turn.\n"
            + "     */\n"
            + "    val G: LongArray = longArrayOf(\n" + g + "    )\n\n"
            + "    /**\n"
            + "     * For each q from Q_MIN to Q_MAX, 5^q as 128 bits with its leading bit set, truncated where q >= 0 and\n"
            + "     * rounded up where q < 0: its upper 64 bits and its lower 64 bits, in turn.\n"
            + "     */\n"
            + "    val FIVE: LongArray = longArrayOf(\n" + five + "    )\n"
            + "}\n";
    }

    /** [value] as a Kotlin Long literal: Kotlin reads -9223372036854775808L as out of range. */
    private static String literal(long value) {
        return value == Long.MIN_VALUE ? "Long.MIN_VALUE" : value + "L";
    }

    /** floor(10^e × 2^-r) + 1, r = floor(log2(10^e)) - 125: 10^e scaled to 126 bits, rounded up. */
    private static BigInteger schubfachPower(int e) {
        int beta = floorLog2PowerOfTen(e);
        int r = beta - 125;
        BigInteger scaled;
        if (e >= 0) {
            BigInteger p = BigInteger.TEN.pow(e);
            scaled = r >= 0 ? p.shiftRight(r) : p.shiftLeft(-r);
        } else {
            scaled = BigInteger.ONE.shiftLeft(-r).divide(BigInteger.TEN.pow(-e));
        }
        BigInteger g = scaled.add(BigInteger.ONE);
        if (g.bitLength() != 126) throw new IllegalStateException("g for 10^" + e + " has " + g.bitLength() + " bits");
        return g;
    }

    /** floor(log2(10^e)), exactly. */
    private static int floorLog2PowerOfTen(int e) {
        if (e >= 0) return BigInteger.TEN.pow(e).bitLength() - 1;
        // 10^e = 1 / 10^-e, which is no power of two: floor(log2) = -ceil(log2(10^-e)) = -bitLength(10^-e).
        return -BigInteger.TEN.pow(-e).bitLength();
    }

    /** 5^q in 128 bits, its leading bit the 128th: truncated where q >= 0, and for q < 0 as fast_float's tables have it. */
    private static BigInteger lemirePower(int q) {
        if (q >= 0) {
            BigInteger p = BigInteger.valueOf(5).pow(q);
            int bits = p.bitLength();
            return bits <= 128 ? p.shiftLeft(128 - bits) : p.shiftRight(bits - 128);
        }
        BigInteger p = BigInteger.valueOf(5).pow(-q);
        int z = p.bitLength();
        int b = q >= -27 ? z + 127 : 2 * z + 128;
        BigInteger c = BigInteger.ONE.shiftLeft(b).divide(p).add(BigInteger.ONE);
        while (c.bitLength() > 128) c = c.shiftRight(1);
        return c;
    }
}
